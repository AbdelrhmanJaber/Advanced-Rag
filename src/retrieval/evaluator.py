from typing import Any, Dict, List, Optional, Tuple

import ollama

logger = logging.getLogger(__name__)


# =============================================================================
# Deterministic Citation Auditor
# =============================================================================

@dataclass
class CitationAudit:
    """Deterministic, rule-based verification of citations (Zero LLM bias)."""
    total_citations: int
    valid_citations: int
    invalid_citations: List[str]
    cited_source_indices: List[int]
    uncited_source_indices: List[int]
    citation_density_per_100_words: float
    is_valid: bool

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


def audit_citations(answer: str, num_sources: int) -> CitationAudit:
    """
    Deterministically audits inline citations without calling an LLM:
      - Validates syntax: matches patterns like [Source 1] or [Source 1, Page 3]
      - Detects phantom/hallucinated source IDs (e.g., [Source 7] when only 3 sources were retrieved)
      - Computes source coverage and citation density
    """
    pattern = re.compile(r"\[Source\s+(\d+)(?:,\s*Page\s+\d+)?\]", re.IGNORECASE)
    matches = pattern.findall(answer)

    total_citations = len(matches)
    valid_citations = 0
    invalid_citations: List[str] = []
    cited_indices: set[int] = set()

    for m in matches:
        idx = int(m)
        if 1 <= idx <= num_sources:
            valid_citations += 1
            cited_indices.add(idx)
        else:
            invalid_citations.append(f"[Source {idx}]")

    words = answer.split()
    word_count = len(words)
    density = round((total_citations / max(word_count, 1)) * 100, 2)

    all_indices = set(range(1, num_sources + 1))
    uncited = sorted(list(all_indices - cited_indices))

    # Valid if at least one citation exists (if sources provided) and NO invalid citations exist
    is_valid = (len(invalid_citations) == 0) and (total_citations > 0 if num_sources > 0 else True)

    return CitationAudit(
        total_citations=total_citations,
        valid_citations=valid_citations,
        invalid_citations=invalid_citations,
        cited_source_indices=sorted(list(cited_indices)),
        uncited_source_indices=uncited,
        citation_density_per_100_words=density,
        is_valid=is_valid,
    )


# =============================================================================
# Judge Evaluation Result Dataclass
# =============================================================================

@dataclass
class EvaluationResult:
    """Complete multi-criteria RAG evaluation report."""
    faithfulness_score: float  # 0.0 - 1.0 (faithfulness to context)
    faithfulness_reasoning: str
    relevance_score: float     # 0.0 - 1.0 (answers the user query)
    relevance_reasoning: str
    conflict_handling_score: float  # 0.0 - 1.0 (proper handling of conflicting sources)
    conflict_handling_reasoning: str
    citation_audit: CitationAudit
    overall_score: float       # Composite weighted score (0.0 - 1.0)
    passed: bool               # Overall pass/fail threshold check
    same_model_bias_warning: bool
    synthesis_model: str
    judge_model: str
    evaluation_time_ms: float
    raw_judge_response: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["citation_audit"] = self.citation_audit.to_dict()
        return data


# =============================================================================
# LLM Judge Prompts (Decomposed Atomic Criteria + Chain-of-Thought)
# =============================================================================

JUDGE_SYSTEM_PROMPT = """You are an impartial, highly rigorous AI evaluation judge.
Your role is to evaluate a candidate answer generated by a RAG system against the provided Reference Context and User Query.

You must operate under strict EVALUATION PRINCIPLES to prevent cognitive bias:
1. ANONYMITY: Evaluate the candidate answer strictly as an anonymous submission. Disregard writing style, eloquence, or assumed author.
2. ATOMIC DECOMPOSITION: Evaluate each criterion independently. A well-written answer with high relevance can still fail Faithfulness if it hallucinates unstated facts.
3. REASONING-FIRST: You must write your factual analysis and quote verifying evidence before assigning any numerical rating.
4. ZERO TOLERANCE FOR UNGROUNDED CLAIMS: Every factual claim in the candidate answer must be directly supported by the cited reference chunk in the context.
5. CONFLICT HANDLING COMPLIANCE: If the context contains contradictory data or conflicting specifications, the candidate answer MUST highlight or report the conflict. If the answer arbitrarily picks one or synthesizes an unsupported compromise, score conflict handling low.

You must return a valid, parseable JSON object matching the schema below:
{
  "faithfulness": {
    "reasoning": "Step-by-step verification of claims against context passages...",
    "score": 0.0 to 1.0
  },
  "answer_relevance": {
    "reasoning": "Assessment of whether the answer directly and completely answers the user query...",
    "score": 0.0 to 1.0
  },
  "conflict_handling": {
    "reasoning": "Assessment of whether contradictions between sources were identified and reported...",
    "score": 0.0 to 1.0
  }
}
"""


def build_judge_prompt(query: str, formatted_context: str, candidate_answer: str) -> str:
    """
    Builds the isolated double-blind user prompt for the judge LLM.
    """
    clean_context = formatted_context.strip() if formatted_context else "(No context provided)"
    return (
        f"<reference_context>\n"
        f"{clean_context}\n"
        f"</reference_context>\n\n"
        f"<user_query>\n"
        f"{query.strip()}\n"
        f"</user_query>\n\n"
        f"<candidate_answer>\n"
        f"{candidate_answer.strip()}\n"
        f"</candidate_answer>\n\n"
        f"<evaluation_task>\n"
        f"Perform an atomic evaluation of the candidate answer against the reference context and user query. "
        f"Output your verdict strictly as a JSON object with 'faithfulness', 'answer_relevance', and 'conflict_handling'."
        f"</evaluation_task>"
    )


# =============================================================================
# RAG Judge Implementation
# =============================================================================

class RAGJudge:
    """
    Anti-Biased LLM-as-a-Judge for RAG synthesis evaluation.
    
    Anti-Biasing Techniques Employed:
      1. Model Decoupling & Warning: Encourages disjoint judge models and warns
         when generator and judge share the same model.
      2. Deterministic Rule Pre-Validation: Audits citation syntax and valid bounds
         programmatically without relying on an LLM.
      3. Atomic Task Decomposition: Scores Faithfulness, Relevance, and Conflict
         Handling independently rather than using holistic subjective 1-10 ratings.
      4. Double-Blind Anonymization: Evaluates text inside <candidate_answer> without
         model attribution or hints.
      5. Reasoning-First JSON Schema: Forces step-by-step evidence checking before
         numerical scoring to eliminate post-hoc confirmation bias.
    """

    def __init__(
        self,
        default_judge_model: str = "qwen2.5:latest",
        min_faithfulness: float = 0.80,
        min_relevance: float = 0.80,
        min_conflict_handling: float = 0.70,
    ) -> None:
        self.default_judge_model = default_judge_model
        self.min_faithfulness = min_faithfulness
        self.min_relevance = min_relevance
        self.min_conflict_handling = min_conflict_handling

    def evaluate(
        self,
        query: str,
        formatted_context: str,
        candidate_answer: str,
        num_sources: int,
        synthesis_model: str = "llama3.2:latest",
        judge_model: Optional[str] = None,
    ) -> EvaluationResult:
        """
        Executes hybrid deterministic + LLM evaluation of the candidate answer.
        """
        active_judge = judge_model or self.default_judge_model
        same_model_bias = (active_judge == synthesis_model)

        if same_model_bias:
            logger.warning(
                f"Same-Model Bias Warning: Both generator and judge are '{synthesis_model}'. "
                f"Consider using a disjoint model (e.g. qwen2.5, mistral, or claude/gpt-4) for unbiased evaluation."
            )

        # 1. Deterministic Rule-Based Pre-Audit (100% unbiased)
        citation_audit = audit_citations(candidate_answer, num_sources)

        # 2. Build isolated judge prompt
        user_prompt = build_judge_prompt(
            query=query,
            formatted_context=formatted_context,
            candidate_answer=candidate_answer,
        )

        t_start = time.perf_counter()
        raw_response_text = ""
        faith_score = 0.0
        faith_reason = ""
        rel_score = 0.0
        rel_reason = ""
        conflict_score = 1.0  # default neutral if no conflicts detected
        conflict_reason = ""

        try:
            resp: Any = ollama.chat(
                model=active_judge,
                messages=[
                    {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
                format="json",
            )

            if hasattr(resp, "message") and hasattr(resp.message, "content"):
                raw_response_text = str(resp.message.content or "")
            elif isinstance(resp, dict):
                msg = resp.get("message", {})
                raw_response_text = str(msg.get("content", "")) if isinstance(msg, dict) else str(getattr(msg, "content", ""))

            parsed = self._extract_json(raw_response_text)
            if parsed:
                faith_dict = parsed.get("faithfulness", {})
                if isinstance(faith_dict, dict):
                    faith_score = float(faith_dict.get("score", 0.0))
                    faith_reason = str(faith_dict.get("reasoning", ""))

                rel_dict = parsed.get("answer_relevance", {})
                if isinstance(rel_dict, dict):
                    rel_score = float(rel_dict.get("score", 0.0))
                    rel_reason = str(rel_dict.get("reasoning", ""))

                conf_dict = parsed.get("conflict_handling", {})
                if isinstance(conf_dict, dict):
                    conflict_score = float(conf_dict.get("score", 1.0))
                    conflict_reason = str(conf_dict.get("reasoning", ""))
            else:
                faith_reason = "Failed to parse structured JSON from judge."
                rel_reason = "Failed to parse structured JSON from judge."

        except Exception as e:
            logger.error(f"Error during LLM Judge evaluation: {e}")
            faith_reason = f"Judge execution error: {e}"
            rel_reason = f"Judge execution error: {e}"
            conflict_reason = f"Judge execution error: {e}"

        eval_time_ms = (time.perf_counter() - t_start) * 1000

        # 3. Composite Weighted Scoring
        # Deterministic citation validity accounts for 20% of the overall score
        citation_component = 1.0 if citation_audit.is_valid else 0.0
        overall_score = round(
            (0.40 * faith_score) + (0.25 * rel_score) + (0.15 * conflict_score) + (0.20 * citation_component),
            3,
        )

        passed = (
            faith_score >= self.min_faithfulness
            and rel_score >= self.min_relevance
            and conflict_score >= self.min_conflict_handling
            and citation_audit.is_valid
        )

        return EvaluationResult(
            faithfulness_score=round(faith_score, 3),
            faithfulness_reasoning=faith_reason,
            relevance_score=round(rel_score, 3),
            relevance_reasoning=rel_reason,
            conflict_handling_score=round(conflict_score, 3),
            conflict_handling_reasoning=conflict_reason,
            citation_audit=citation_audit,
            overall_score=overall_score,
            passed=passed,
            same_model_bias_warning=same_model_bias,
            synthesis_model=synthesis_model,
            judge_model=active_judge,
            evaluation_time_ms=round(eval_time_ms, 2),
            raw_judge_response=raw_response_text,
        )

    @staticmethod
    def _extract_json(text: str) -> Optional[Dict[str, Any]]:
        """Robustly extracts JSON from raw LLM output even if surrounded by markdown fences."""
        text = text.strip()
        if not text:
            return None

        # Strip markdown ```json ... ``` blocks
        if "```" in text:
            match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
            if match:
                text = match.group(1).strip()

        try:
            return json.loads(text)
        except json.JSONDecodeError:
            # Fallback: find outer matching braces { ... }
            start = text.find("{")
            end = text.rfind("}")
            if start != -1 and end != -1 and end > start:
                try:
                    return json.loads(text[start : end + 1])
                except json.JSONDecodeError:
                    return None
            return None
